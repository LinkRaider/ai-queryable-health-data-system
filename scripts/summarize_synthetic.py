#!/usr/bin/env python3
"""Render deterministic evidence for human review of synthetic patterns."""

from __future__ import annotations

import argparse
import hashlib
import statistics
import sys
from collections import Counter, defaultdict
from datetime import UTC, timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from health_data.generator import (  # noqa: E402
    ActivityState,
    GenerationConfig,
    build_day_plan,
    canonical_timestamp,
    device_off_windows,
    generate_events,
    generate_profiles,
)


def _digest(events: list) -> str:
    digest = hashlib.sha256()
    for event in events:
        digest.update(
            f"{event.event_id}|{event.value}|{event.activity_state.value}\n".encode()
        )
    return digest.hexdigest()


def _representative_profile_ids(profiles: tuple) -> list[str]:
    lowest = min(profiles, key=lambda profile: profile.resting_baseline_bpm)
    highest = max(profiles, key=lambda profile: profile.resting_baseline_bpm)
    middle = profiles[len(profiles) // 2]
    return [lowest.user_id, middle.user_id, highest.user_id]


def _find_timeline(profiles: tuple, config: GenerationConfig) -> tuple:
    for profile in profiles:
        local_day = config.window_start.astimezone(profile.timezone).date()
        for offset in range(config.days + 1):
            day = local_day + timedelta(days=offset)
            plan = build_day_plan(profile, day, config)
            day_start_utc = plan.workout.start.replace(
                hour=0, minute=0, second=0
            ).astimezone(UTC) if plan.workout is not None else None
            full_day_in_window = (
                day_start_utc is not None
                and day_start_utc >= config.window_start.astimezone(UTC)
                and day_start_utc + timedelta(days=1) <= config.window_end.astimezone(UTC)
            )
            intervals_do_not_overlap = (
                plan.workout is not None
                and plan.device_off is not None
                and (
                    plan.workout.end <= plan.device_off.start
                    or plan.device_off.end <= plan.workout.start
                )
            )
            if full_day_in_window and intervals_do_not_overlap:
                return profile, day, plan
    raise RuntimeError("default configuration did not produce a workout/off timeline")


def render() -> str:
    config = GenerationConfig()
    profiles = generate_profiles(config)
    events = list(generate_events(config))
    by_user = defaultdict(list)
    by_state = defaultdict(list)
    for event in events:
        by_user[event.user_id].append(event)
        by_state[event.activity_state].append(event)

    lines = [
        "# Deterministic synthetic sample",
        "",
        "Generated by `python3 scripts/summarize_synthetic.py --output "
        "docs/synthetic-sample.md` using the default fixed configuration.",
        "These are synthetic engineering patterns, not clinically validated measurements.",
        "",
        "## Reproducibility snapshot",
        "",
        f"- Events: {len(events):,}",
        f"- Users: {len(profiles)}",
        f"- Window: `{canonical_timestamp(config.window_start)}` to "
        f"`{canonical_timestamp(config.window_end)}`",
        f"- Seed: `{config.seed}`",
        f"- Event/value/state SHA-256: `{_digest(events)}`",
        "",
        "## Population pattern summary",
        "",
        "| State | Events | Mean recorded BPM |",
        "| --- | ---: | ---: |",
    ]
    for state in ActivityState:
        values = [event.value for event in by_state[state]]
        lines.append(f"| `{state.value}` | {len(values):,} | {statistics.fmean(values):.1f} |")

    lines.extend(
        [
            "",
            "## Distinguishable profiles",
            "",
            "| User | Time zone | Rest baseline | Wake | Bed | Activity boost | Workout boost |",
            "| --- | --- | ---: | ---: | ---: | ---: | ---: |",
        ]
    )
    profile_by_id = {profile.user_id: profile for profile in profiles}
    for user_id in _representative_profile_ids(profiles):
        profile = profile_by_id[user_id]
        lines.append(
            f"| `{profile.user_id}` | `{profile.timezone_name}` | "
            f"{profile.resting_baseline_bpm:.1f} | "
            f"{profile.wake_minute // 60:02d}:{profile.wake_minute % 60:02d} | "
            f"{profile.bedtime_minute // 60:02d}:{profile.bedtime_minute % 60:02d} | "
            f"+{profile.ordinary_activity_boost_bpm:.1f} | "
            f"+{profile.workout_boost_bpm:.1f} |"
        )

    profile, day, plan = _find_timeline(profiles, config)
    day_events = [
        event
        for event in by_user[profile.user_id]
        if event.observed_at.astimezone(profile.timezone).date() == day
    ]
    segments: list[tuple] = []
    for event in day_events:
        local_event = event.observed_at.astimezone(profile.timezone)
        if not segments:
            segments.append([event.activity_state, local_event, local_event, [event.value]])
            continue
        previous = segments[-1]
        gap = (local_event.astimezone(UTC) - previous[2].astimezone(UTC)).total_seconds()
        if previous[0] is event.activity_state and gap <= 10 * 60:
            previous[2] = local_event
            previous[3].append(event.value)
        else:
            segments.append([event.activity_state, local_event, local_event, [event.value]])

    assert plan.workout is not None
    assert plan.device_off is not None
    off_start = plan.device_off.start.astimezone(UTC)
    off_end = plan.device_off.end.astimezone(UTC)
    user_instants = [event.observed_at.astimezone(UTC) for event in by_user[profile.user_id]]
    before = max(instant for instant in user_instants if instant < off_start)
    after = min(instant for instant in user_instants if instant >= off_end)

    lines.extend(
        [
            "",
            f"## Representative local timeline: `{profile.user_id}` on `{day}`",
            "",
            f"Time zone: `{profile.timezone_name}`. Planned workout: "
            f"`{plan.workout.start:%H:%M}`–`{plan.workout.end:%H:%M}`. "
            f"Device off: `{plan.device_off.start:%H:%M}`–`{plan.device_off.end:%H:%M}`.",
            "",
            "| Observed segment | State | Readings | Mean recorded BPM |",
            "| --- | --- | ---: | ---: |",
        ]
    )
    for state, start, end, values in segments:
        lines.append(
            f"| `{start:%H:%M:%S}`–`{end:%H:%M:%S}` | `{state.value}` | "
            f"{len(values)} | {statistics.fmean(values):.1f} |"
        )

    lines.extend(
        [
            "",
            "## Explicit no-reading gap",
            "",
            f"- Device-off interval: `{plan.device_off.start.isoformat(timespec='seconds')}` "
            f"to `{plan.device_off.end.isoformat(timespec='seconds')}`.",
            f"- Nearest reading before: `{before.astimezone(profile.timezone).isoformat(timespec='seconds')}`.",
            f"- Nearest reading after: `{after.astimezone(profile.timezone).isoformat(timespec='seconds')}`.",
            f"- Observed reading-to-reading gap: `{(after - before).total_seconds() / 60:.1f}` minutes.",
            f"- Events inside the device-off interval: "
            f"`{sum(off_start <= instant < off_end for instant in user_instants)}`.",
            "",
            "## Coverage",
            "",
            f"- Users with at least one explicit device-off interval: "
            f"{sum(bool(device_off_windows(profile, config)) for profile in profiles)}/"
            f"{len(profiles)}.",
            f"- Activity states present: "
            f"{', '.join(sorted(state.value for state in Counter(event.activity_state for event in events)))}.",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path)
    args = parser.parse_args()
    rendered = render()
    if args.output is None:
        print(rendered)
        return
    args.output.write_text(rendered, encoding="utf-8")


if __name__ == "__main__":
    main()
